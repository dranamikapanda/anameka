// Generates supabase/seed.sql from lib/content/*.json. Run: node scripts/generate-seed.mjs
import { readFileSync, writeFileSync } from "fs";
const read = (f) => JSON.parse(readFileSync(new URL(`../lib/content/${f}`, import.meta.url), "utf8"));
const q = (v) => v == null ? "null" : `'${String(v).replace(/'/g, "''")}'`;
const j = (v) => `${q(JSON.stringify(v ?? []))}::jsonb`;
const arr = (v) => `array[${(v ?? []).map(q).join(",")}]::text[]`;
const words = (h) => Math.max(1, Math.round(h.replace(/<[^>]+>/g, " ").trim().split(/\s+/).length / 200));
const out = ["-- Generated by scripts/generate-seed.mjs. Safe to re-run: uses ON CONFLICT DO NOTHING.", "begin;"];

out.push(`insert into public.site_settings (key, value) values ('global', ${q(JSON.stringify(read("site.json")))}::jsonb) on conflict (key) do nothing;`);

read("services.json").forEach((s, i) => out.push(
  `insert into public.services (slug,title,short_description,icon,intro,what_is,process,who_for,procedure,benefits,limitations,faqs,seo_title,seo_description,sort_order,status) values (${[
    q(s.slug), q(s.title), q(s.short_description), q(s.icon), q(s.intro), q(s.what_is), q(s.process), q(s.who_for),
    j(s.procedure), j(s.benefits), j(s.limitations), j(s.faqs), q(s.seo_title), q(s.seo_description), (i + 1) * 10, "'published'"].join(",")}) on conflict (slug) do nothing;`));

read("programmes.json").forEach((p, i) => out.push(
  `insert into public.programmes (slug,title,audience,audience_key,tagline,summary,intro,pillars,includes,for_whom,format,price_note,price_inr,cta_label,whatsapp_keyword,poster_url,poster_alt,faqs,seo_title,seo_description,sort_order,status) values (${[
    q(p.slug), q(p.title), q(p.audience), q(p.audience_key), q(p.tagline), q(p.summary), q(p.intro), j(p.pillars), j(p.includes), j(p.for_whom),
    q(p.format), q(p.price_note), p.price_inr ?? "null", q(p.cta_label), q(p.whatsapp_keyword), q(p.poster_url), q(p.poster_alt), j(p.faqs), q(p.seo_title), q(p.seo_description), (i + 1) * 10, "'published'"].join(",")}) on conflict (slug) do nothing;`));

// Drafts needing confirmation: visible in Admin, kept off the public site until approved.
read("testimonials-draft.json").forEach((t) => out.push(
  `insert into public.testimonials (kind,client_name,service_slug,quote,permission_confirmed,permission_note,status) select ${[q(t.kind), q(t.client_name), q(t.service_slug), q(t.quote), "false", q(t.permission_note), "'draft'"].join(",")} where not exists (select 1 from public.testimonials where quote = ${q(t.quote)});`));
read("social-draft.json").forEach((s) => out.push(
  `insert into public.social_links (platform,url,status) select ${q(s.platform)},${q(s.url)},'draft' where not exists (select 1 from public.social_links where url = ${q(s.url)});`));
read("gallery-draft.json").forEach((g, i) => out.push(
  `insert into public.gallery_items (category,title,alt,image_url,sort_order,status) select 'flyers',${q(g.title)},${q(g.alt)},${q(g.image_url)},${(i + 1) * 10},'draft' where not exists (select 1 from public.gallery_items where image_url = ${q(g.image_url)});`));

read("blog-categories.json").forEach((c) => out.push(`insert into public.blog_categories (slug,name) values (${q(c.slug)},${q(c.name)}) on conflict do nothing;`));

read("blog-posts.json").forEach((p) => out.push(
  `insert into public.blog_posts (slug,title,excerpt,body,cover_url,cover_alt,category_slug,tags,featured,reading_minutes,status,publish_at) values (${[
    q(p.slug), q(p.title), q(p.excerpt), q(p.body), q(p.cover_url), q(p.cover_alt), q(p.category_slug), arr(p.tags), p.featured, words(p.body), "'published'", q(p.publish_at)].join(",")}) on conflict (slug) do nothing;`));

read("faqs.json").forEach((f, i) => out.push(`insert into public.faqs (question,answer,topic,sort_order,status) select ${q(f.question)},${q(f.answer)},${q(f.topic)},${(i + 1) * 10},'published' where not exists (select 1 from public.faqs where question = ${q(f.question)});`));

read("legal.json").forEach((l) => out.push(`insert into public.legal_pages (slug,title,body,status) values (${q(l.slug)},${q(l.title)},${q(l.body)},'published') on conflict (slug) do nothing;`));

// Profile: verified sections publish; placeholders stay in the admin panel, unverified.
read("profile.json").sections.forEach((s, i) => out.push(
  `insert into public.profile_sections (slug,title,body,verified,sort_order,status) values (${q(s.slug)},${q(s.title)},${q(s.body)},${s.verified},${(i + 1) * 10},'published') on conflict (slug) do nothing;`));

out.push("commit;", "",
  "-- After creating your first user in Supabase → Authentication, promote them:",
  "-- update public.profiles set role = 'admin' where id = (select id from auth.users where email = 'YOUR-EMAIL');");
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out.join("\n") + "\n");
console.log(`seed.sql written (${out.length} statements)`);
