import json
import re
from pathlib import Path

ROOT = Path(__file__).parent.parent
CONTENT = ROOT / "lib" / "content"

def read(f):
    with open(CONTENT / f, "r", encoding="utf-8") as fp:
        return json.load(fp)

def q(v):
    if v is None:
        return "null"
    return "'" + str(v).replace("'", "''") + "'"

def j(v):
    val = v if v is not None else []
    json_str = json.dumps(val, ensure_ascii=False)
    return f"{q(json_str)}::jsonb"

def arr(v):
    items = v if v is not None else []
    return f"array[{','.join(q(x) for x in items)}]::text[]"

def words(h):
    stripped = re.sub(r'<[^>]+>', ' ', h).strip()
    return max(1, round(len(stripped.split()) / 200))

out = [
    "-- Generated by scripts/generate_seed.py. Safe to re-run: uses ON CONFLICT DO NOTHING.",
    "begin;"
]

out.append(f"insert into public.site_settings (key, value) values ('global', {q(json.dumps(read('site.json')))}::jsonb) on conflict (key) do nothing;")

for i, s in enumerate(read("services.json")):
    fields = [
        q(s.get("slug")), q(s.get("title")), q(s.get("short_description")), q(s.get("icon")),
        q(s.get("intro")), q(s.get("what_is")), q(s.get("process")), q(s.get("who_for")),
        j(s.get("procedure")), j(s.get("benefits")), j(s.get("limitations")), j(s.get("faqs")),
        q(s.get("seo_title")), q(s.get("seo_description")), str((i + 1) * 10), "'published'"
    ]
    out.append(f"insert into public.services (slug,title,short_description,icon,intro,what_is,process,who_for,procedure,benefits,limitations,faqs,seo_title,seo_description,sort_order,status) values ({','.join(fields)}) on conflict (slug) do nothing;")

for i, p in enumerate(read("programmes.json")):
    fields = [
        q(p.get("slug")), q(p.get("title")), q(p.get("audience")), q(p.get("audience_key")),
        q(p.get("tagline")), q(p.get("summary")), q(p.get("intro")), j(p.get("pillars")),
        j(p.get("includes")), j(p.get("for_whom")), q(p.get("format")), q(p.get("price_note")),
        str(p.get("price_inr")) if p.get("price_inr") is not None else "null",
        q(p.get("cta_label")), q(p.get("whatsapp_keyword")), q(p.get("poster_url")),
        q(p.get("poster_alt")), j(p.get("faqs")), q(p.get("seo_title")), q(p.get("seo_description")),
        str((i + 1) * 10), "'published'"
    ]
    out.append(f"insert into public.programmes (slug,title,audience,audience_key,tagline,summary,intro,pillars,includes,for_whom,format,price_note,price_inr,cta_label,whatsapp_keyword,poster_url,poster_alt,faqs,seo_title,seo_description,sort_order,status) values ({','.join(fields)}) on conflict (slug) do nothing;")

for t in read("testimonials-draft.json"):
    fields = [q(t.get("kind")), q(t.get("client_name")), q(t.get("service_slug")), q(t.get("quote")), "'false'", q(t.get("permission_note")), "'draft'"]
    out.append(f"insert into public.testimonials (kind,client_name,service_slug,quote,permission_confirmed,permission_note,status) select {','.join(fields)} where not exists (select 1 from public.testimonials where quote = {q(t.get('quote'))});")

for s in read("social-draft.json"):
    out.append(f"insert into public.social_links (platform,url,status) select {q(s.get('platform'))},{q(s.get('url'))},'draft' where not exists (select 1 from public.social_links where url = {q(s.get('url'))});")

for i, g in enumerate(read("gallery-draft.json")):
    out.append(f"insert into public.gallery_items (category,title,alt,image_url,sort_order,status) select 'flyers',{q(g.get('title'))},{q(g.get('alt'))},{q(g.get('image_url'))},{(i + 1) * 10},'draft' where not exists (select 1 from public.gallery_items where image_url = {q(g.get('image_url'))});")

for c in read("blog-categories.json"):
    out.append(f"insert into public.blog_categories (slug,name) values ({q(c.get('slug'))},{q(c.get('name'))}) on conflict do nothing;")

for p in read("blog-posts.json"):
    fields = [
        q(p.get("slug")), q(p.get("title")), q(p.get("excerpt")), q(p.get("body")),
        q(p.get("cover_url")), q(p.get("cover_alt")), q(p.get("category_slug")),
        arr(p.get("tags")), "true" if p.get("featured") else "false",
        str(words(p.get("body", ""))), "'published'", q(p.get("publish_at"))
    ]
    out.append(f"insert into public.blog_posts (slug,title,excerpt,body,cover_url,cover_alt,category_slug,tags,featured,reading_minutes,status,publish_at) values ({','.join(fields)}) on conflict (slug) do nothing;")

for i, f in enumerate(read("faqs.json")):
    out.append(f"insert into public.faqs (question,answer,topic,sort_order,status) select {q(f.get('question'))},{q(f.answer if hasattr(f, 'answer') else f.get('answer'))},{q(f.get('topic'))},{(i + 1) * 10},'published' where not exists (select 1 from public.faqs where question = {q(f.get('question'))});")

for l in read("legal.json"):
    out.append(f"insert into public.legal_pages (slug,title,body,status) values ({q(l.get('slug'))},{q(l.get('title'))},{q(l.get('body'))},'published') on conflict (slug) do nothing;")

for i, s in enumerate(read("profile.json").get("sections", [])):
    fields = [q(s.get("slug")), q(s.get("title")), q(s.get("body")), "true" if s.get("verified") else "false", str((i + 1) * 10), "'published'"]
    out.append(f"insert into public.profile_sections (slug,title,body,verified,sort_order,status) values ({','.join(fields)}) on conflict (slug) do nothing;")

out.extend([
    "commit;",
    "",
    "-- After creating your first user in Supabase → Authentication, promote them:",
    "-- update public.profiles set role = 'admin' where id = (select id from auth.users where email = 'YOUR-EMAIL');"
])

(ROOT / "supabase" / "seed.sql").write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"seed.sql successfully regenerated ({len(out)} statements)")
